/**
 * Expo config plugin: gives Android's own cloud backup / device transfer an explicit allowlist
 * (TASK-023, Part B; pattern from GymDiary's plugin of the same name).
 *
 * Why: the app had `android:allowBackup="true"` and no rules, so Android could copy the WHOLE app
 * data to the user's Google account — including the MMKV store that holds the AI API keys, and
 * device-specific state such as the automatic-backup folder grant (which does not survive a
 * reinstall, so restoring it would only produce a stale setting).
 *
 * What is backed up: the SQLite database (SQLite/) and the MMKV stores that are real user data.
 * What is excluded: `ai` (API keys), `notifications-store` (scheduled-notification ids, useless
 * after a reinstall) and `auto-backup` (folder grant and bookkeeping).
 *
 * MMKV keeps every store as files/mmkv/<id> plus files/mmkv/<id>.crc (react-native-mmkv roots
 * at getFilesDir()/mmkv). The android/ folder is regenerated by `expo prebuild`, so this plugin
 * re-applies everything on every prebuild.
 */
const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const RULES_RES_NAME = 'germanbuddy_backup_rules';
const LEGACY_RES_NAME = 'germanbuddy_backup_rules_legacy';

const INCLUDED_PATHS = ['SQLite/', 'mmkv/'];
const EXCLUDED_MMKV_STORES = ['ai', 'notifications-store', 'auto-backup'];

function ruleLines(indent) {
  const lines = INCLUDED_PATHS.map((p) => `${indent}<include domain="file" path="${p}" />`);
  for (const id of EXCLUDED_MMKV_STORES) {
    lines.push(`${indent}<exclude domain="file" path="mmkv/${id}" />`);
    lines.push(`${indent}<exclude domain="file" path="mmkv/${id}.crc" />`);
  }
  return lines.join('\n');
}

// API 31+ — <application android:dataExtractionRules="...">
function buildDataExtractionRules() {
  return `<?xml version="1.0" encoding="utf-8"?>
<data-extraction-rules>
    <cloud-backup>
${ruleLines('        ')}
    </cloud-backup>
    <device-transfer>
${ruleLines('        ')}
    </device-transfer>
</data-extraction-rules>
`;
}

// API <= 30 — <application android:fullBackupContent="...">
function buildFullBackupContent() {
  return `<?xml version="1.0" encoding="utf-8"?>
<full-backup-content>
${ruleLines('    ')}
</full-backup-content>
`;
}

/** Sets the three attributes on the manifest's <application> element (object form from xml2js). */
function setBackupAttributes(application) {
  application.$['android:allowBackup'] = 'true';
  application.$['android:dataExtractionRules'] = `@xml/${RULES_RES_NAME}`;
  application.$['android:fullBackupContent'] = `@xml/${LEGACY_RES_NAME}`;
  return application;
}

function withBackupXmlFiles(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const xmlDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(path.join(xmlDir, `${RULES_RES_NAME}.xml`), buildDataExtractionRules());
      fs.writeFileSync(path.join(xmlDir, `${LEGACY_RES_NAME}.xml`), buildFullBackupContent());
      return cfg;
    },
  ]);
}

function withBackupManifestAttributes(config) {
  return withAndroidManifest(config, (cfg) => {
    setBackupAttributes(AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults));
    return cfg;
  });
}

function withAndroidBackupRules(config) {
  config = withBackupXmlFiles(config);
  config = withBackupManifestAttributes(config);
  return config;
}

module.exports = withAndroidBackupRules;
module.exports.buildDataExtractionRules = buildDataExtractionRules;
module.exports.buildFullBackupContent = buildFullBackupContent;
module.exports.setBackupAttributes = setBackupAttributes;
