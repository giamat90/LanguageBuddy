/**
 * Generates the three "active language" seam files. One language is active per build (one app
 * per language), and Metro needs static import paths, so selection is done by generating these:
 *   src/data/wordbank/active.ts       the six level files of the language
 *   src/i18n/wordContentLoaders.ts    its translated word content (one loader per UI language)
 *   src/languages/active.ts           its LanguagePack
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const LEVELS = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'];
const HEADER = '// GENERATED by scripts/set-active-language.mjs — do not edit.';

/** Returns { problems } and writes the seams only when there are none. */
export function setActiveLanguage(code, { root, src, nativeCodes }) {
  const problems = [];
  if (!/^[a-z]{2,3}$/.test(code ?? '')) problems.push(`"${code}" is not a language code`);
  const cfgPath = join(root, String(code), 'language.json');
  if (!existsSync(cfgPath)) problems.push(`unknown language "${code}": ${cfgPath} not found`);
  if (!existsSync(join(src, 'languages', `${code}.ts`))) problems.push(`unknown language "${code}": src/languages/${code}.ts not found`);
  if (problems.length) return { problems };

  const cfg = JSON.parse(readFileSync(cfgPath, 'utf8'));
  const levels = cfg.levels ?? LEVELS;
  if (levels.join() !== LEVELS.join()) problems.push(`"${code}" cannot be active: it must define all six levels`);
  for (const l of LEVELS) {
    if (!existsSync(join(src, 'data', 'wordbank', code, `${l}.json`))) problems.push(`src/data/wordbank/${code}/${l}.json missing (run build:wordbank)`);
  }
  if (problems.length) return { problems };

  const imports = LEVELS.map((l) => `import ${l.toLowerCase()} from './${code}/${l}.json';`);
  writeFileSync(
    join(src, 'data', 'wordbank', 'active.ts'),
    [HEADER, ...imports, '', `export const LEVEL_FILES = { ${LEVELS.map((l) => `${l}: ${l.toLowerCase()}`).join(', ')} };`, ''].join('\n'),
  );

  const i18nDir = join(src, 'data', 'wordbank', code, 'i18n');
  const langs = existsSync(i18nDir)
    ? readdirSync(i18nDir).filter((f) => f.endsWith('.json')).map((f) => f.replace(/\.json$/, '')).filter((l) => nativeCodes.includes(l)).sort()
    : [];
  const entries = langs.map((l) => `  ${l}: () => require('../data/wordbank/${code}/i18n/${l}.json'),`);
  writeFileSync(
    join(src, 'i18n', 'wordContentLoaders.ts'),
    [
      HEADER,
      "import type { NativeLanguage } from './language';",
      "import type { WordContentTriple } from './wordContent';",
      '',
      'export const WORD_CONTENT_LOADERS: Partial<',
      '  Record<NativeLanguage, () => Record<string, WordContentTriple>>',
      entries.length ? `> = {\n${entries.join('\n')}\n};` : '> = {};',
      '',
    ].join('\n'),
  );

  writeFileSync(join(src, 'languages', 'active.ts'), [HEADER, `export { ${code} as activePack } from './${code}';`, ''].join('\n'));
  return { problems: [] };
}
