import { pickLocalized, type NativeLanguage } from './language';
import { WORD_CONTENT_LOADERS } from './wordContentLoaders';

/**
 * Translated word-bank content for the app languages beyond Italian and English
 * (TASK-025 registers the loaders). Keyed like `entryId()` in data/wordbank:
 * `<LEVEL>:<word lower-cased, spaces as dashes>`. Four words (e.g. "essen") exist
 * in two levels, so the level is part of the key whenever it is known.
 */
export type WordField = 'meaning' | 'example' | 'note';
export type WordContentTriple = [meaning: string, example: string, note: string];
type Table = Record<string, WordContentTriple>;
type Loader = () => Table;

const FIELD_INDEX: Record<WordField, 0 | 1 | 2> = { meaning: 0, example: 1, note: 2 };
const LEVELS = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'] as const;

// Lazy: a language's JSON is only evaluated the first time that language is shown.
// The table is generated by the word-bank build from the JSON files that exist.
const LOADERS: Partial<Record<NativeLanguage, Loader>> = { ...WORD_CONTENT_LOADERS };

const tables = new Map<NativeLanguage, Table | null>();

function table(lang: NativeLanguage): Table | null {
  if (tables.has(lang)) return tables.get(lang) ?? null;
  const loader = LOADERS[lang];
  let loaded: Table | null = null;
  if (loader) {
    try {
      loaded = loader();
    } catch (e) {
      console.error(`[wordContent] could not load "${lang}" word content:`, e);
    }
  }
  tables.set(lang, loaded);
  return loaded;
}

/** Test seam: register (or clear, with undefined) a loader and forget what was memoized. */
export function __setLoaderForTests(lang: NativeLanguage, loader: Loader | undefined): void {
  if (loader) LOADERS[lang] = loader;
  else delete LOADERS[lang];
  tables.delete(lang);
}

function slug(word: string): string {
  return word.toLowerCase().replace(/\s+/g, '-');
}

export function getWordContent(
  lang: NativeLanguage,
  word: string,
  level?: string | null,
): WordContentTriple | null {
  if (lang === 'it' || lang === 'en') return null;
  const t = table(lang);
  if (!t) return null;
  const s = slug(word);
  if (level) return t[`${level}:${s}`] ?? null;
  for (const l of LEVELS) {
    const hit = t[`${l}:${s}`];
    if (hit) return hit;
  }
  return null;
}

/**
 * The text of `field` for a word in the learner's language: translated content when it
 * exists, otherwise the Italian/English pair already on the item (English first for
 * the new languages).
 */
export function localizedText(
  lang: NativeLanguage,
  field: WordField,
  ref: { word: string; level?: string | null },
  it: string | null | undefined,
  en: string | null | undefined,
): string | null {
  const local = getWordContent(lang, ref.word, ref.level)?.[FIELD_INDEX[field]] ?? null;
  return pickLocalized(lang, it, en, local);
}
